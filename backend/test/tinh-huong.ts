import { May, TinhHuong, SDT } from './khung.ts';
import { dangNhapCacBen, chaoVaDongY, lapVaKy, chuyenCoc, traThangVaXacNhan, chuanBiGiao, nghiemThuTaiVuon, lenhNganHangVaDoiSoat } from './luong.ts';

type Fn = (may: May, th: TinhHuong) => Promise<void>;
export const DANH_SACH: [string, string, Fn][] = [];
export const them = (ma: string, ten: string, fn: Fn) => DANH_SACH.push([ma, ten, fn]);

them('TH-006', 'HĐ luồng thuận: giao tại vườn, nghiệm thu tại vườn, trả thẳng trước bốc', async (may, th) => {
  const b = await dangNhapCacBen(may);
  await chaoVaDongY(b, th);
  const lc = (await b.nam.get(`/v1/offers/${b.offerId}`)).json;
  th.kiem('GET lời chào (S4): có câu thông báo "Đây chưa phải hợp đồng."', String(lc.thong_bao ?? '').startsWith('Đây chưa phải hợp đồng.'), lc.thong_bao);
  th.kiem('GET lời chào (S2): giá tham khảo và % do backend trả', lc.gia_tham_khao_vnd === null || Number.isInteger(lc.phan_tram_gia_tham_khao), { ref: lc.gia_tham_khao_vnd, pct: lc.phan_tram_gia_tham_khao });
  const d = await lapVaKy(b, th);
  th.bang('P_coc', d.data.tinh.gia_tinh_coc_vnd, '23000');
  th.bang('Cọc C', d.data.tinh.coc_vnd, '13800000');
  th.bang('Phí F', d.data.tinh.phi_vnd, '138000');
  th.bang('Trả thẳng trước bốc', d.data.tinh.tra_thang_vnd, '32200000');
  const pdf = await b.ha.get(`/v1/documents/${b.docId}/file`);
  th.kiem('PDF hợp đồng tải được, bắt đầu %PDF', pdf.status === 200 && pdf.raw.subarray(0, 5).toString() === '%PDF-', pdf.status);
  const meta = (await b.nam.get(`/v1/documents/${b.docId}`)).json;
  const { createHash } = await import('node:crypto');
  th.bang('SHA-256 tệp PDF khớp metadata', createHash('sha256').update(pdf.raw).digest('hex'), meta.file_sha256);
  th.bang('Hai chữ ký trên hợp đồng', (meta.signatures ?? []).length, 2);
  const hanCoc = await may.v<string>(`SELECT extract(epoch FROM due_at - created_at)/3600 FROM core.deadlines WHERE kind='deposit' AND order_id=$1`, [b.orderId]);
  th.bang('Hạn cọc hàng tươi 12 giờ', Math.round(Number(hanCoc)), 12);
  const { hd, g } = await chuyenCoc(b);
  th.bang('VietQR tổng chuyển', hd.total_vnd, '13938000');
  th.bang('Nội dung chuyển', hd.payment_ref, `AGV ${b.orderCode!.replace(/-/g, '')} COC`);
  th.kiem('Webhook ngân hàng được áp', (g[0]?.ket_qua as any)?.http === 200, g);
  let o = (await b.nam.get(`/v1/orders/${b.orderId}`)).json;
  th.bang('Đơn hiệu lực sau cọc', o.status, 'active');
  th.bang('Liên lạc mở đầy đủ', o.lien_lac, 'full');
  const so = (await b.ha.get(`/v1/orders/${b.orderId}/money`)).json;
  th.bang('Cọc đang giữ (sổ)', so.so_cai.find((x: any) => x.account_type === 'deposit_escrow')?.balance_vnd, '13800000');
  th.bang('Phí đang giữ (sổ)', so.so_cai.find((x: any) => x.account_type === 'fee_held')?.balance_vnd, '138000');
  th.bang('Khoản trả thẳng đến hạn', so.khoan_tra_thang[0]?.status, 'due');
  const xn = await traThangVaXacNhan(b, 32200000);
  th.bang('Người bán nhận đủ trả thẳng', xn.status, 'fully_received');
  const kh = (await b.nam.get(`/v1/orders/${b.orderId}/payments`)).json.find((x: any) => x.id === b.paymentId);
  th.kiem('Danh sách khoản (G1): có mã ảnh chứng từ bên mua báo', Array.isArray(kh?.evidence_document_ids) && kh.evidence_document_ids.length === 1, kh?.evidence_document_ids);
  const gk = (b as any).guiLaiKy, gx = (b as any).guiLaiXn;
  th.kiem('Gửi lại lệnh ký cùng mã: trả kết quả đã lưu, không đòi OTP mới', gk.status === 200 && gk.json.replayed === true && gk.json.status === 'awaiting_deposit', { http: gk.status, body: gk.json });
  th.kiem('Gửi lại xác nhận tiền cùng mã: trả kết quả đã lưu', gx.status === 200 && gx.json.replayed === true && gx.json.status === 'fully_received', { http: gx.status, body: gx.json });
  const xe = await chuanBiGiao(b);
  th.bang('Đợt sẵn sàng sau khi có xe', xe.data.delivery_status, 'ready');
  const kq = await nghiemThuTaiVuon(b, [{ kind: 'accepted', qty_kg: 1850 }, { kind: 'downgraded', qty_kg: 120, reason_code: 'TRAY_VO' }, { kind: 'rejected', qty_kg: 30, reason_code: 'DAP' }]);
  th.bang('Kết quả gửi: chờ người bán xác nhận', kq.status, 'awaiting_seller');
  th.bang('Giá trị nghiệm thu', kq.data.gia_tri_vnd, '44350000');
  const dy = await b.nam.ok(`/v1/deliveries/${b.deliveryId}/acceptance/agree`, { pin: '2468' });
  th.bang('Đợt đang vận chuyển sau chốt tại vườn', dy.status, 'in_transit');
  th.bang('Lô con trả lại 30 kg', dy.data.lo_con?.qty_g, '30000');
  th.bang('Lô con loại L2', dy.data.lo_con?.grade_code, 'L2');
  const sl = (await b.nam.get(`/v1/lots/${b.lotId}/qty`)).json;
  th.bang('Sổ lượng đã giao 1.970 kg', sl.delivered, '1970000');
  th.bang('Sổ lượng chuyển lô con 30 kg', sl.moved_to_child, '30000');
  const den = await b.phuc.ok(`/v1/deliveries/${b.deliveryId}/arrival`, { weighed_g: 1950000 });
  th.bang('Hao hụt 20 kg', den.data.hao_hut_g, '20000');
  th.kiem('Hao hụt trong mức cho phép', den.data.vuot_muc === false, den.data);
  const xdd = await b.phuc.ok(`/v1/deliveries/${b.deliveryId}/arrival/confirm`, {});
  th.bang('Đợt đã chốt', xdd.status, 'closed');
  const qt = xdd.data.quyet_toan;
  th.bang('Quyết toán V', qt?.V, '44350000');
  th.bang('Quyết toán N', qt?.N, '44350000');
  th.bang('Chi cọc người bán', qt?.release_vnd, '12150000');
  th.bang('Hoàn cọc bên mua', qt?.refund_vnd, '1650000');
  o = (await b.ha.get(`/v1/orders/${b.orderId}`)).json;
  th.bang('Đơn chờ quyết toán', o.status, 'awaiting_settlement');
  await lenhNganHangVaDoiSoat(b);
  o = (await b.ha.get(`/v1/orders/${b.orderId}`)).json;
  th.bang('Đơn hoàn tất', o.status, 'completed');
  const nhan = await may.v<string>(`SELECT coalesce(sum(e.amount_vnd),0)::text FROM ledger.entries e JOIN ledger.transactions t ON t.id=e.transaction_id JOIN ledger.accounts a ON a.id=e.account_id WHERE t.order_id=$1 AND a.account_type='external' AND a.org_id=(SELECT seller_org_id FROM core.orders WHERE id=$1) AND e.amount_vnd>0`, [b.orderId]);
  th.bang('Người bán thực nhận (sổ cái)', nhan, '44350000');
  const tn = (await b.nam.get(`/v1/orders/${b.orderId}/money`)).json.thuc_nhan;
  th.bang('API /money của người bán: thực nhận (cho màn Tiền đã về)', tn?.nguoi_ban_vnd, '44350000');
  th.kiem('API /money: đã đối soát hết lệnh ngân hàng', tn?.da_xac_minh === true, tn);
  const docs = o.tai_lieu.map((x: any) => x.doc_type);
  th.kiem('Có BBNT và BQT', docs.includes('acceptance_record') && docs.includes('settlement_statement'), docs);
  const phi = (await b.ha.get(`/v1/orders/${b.orderId}/money`)).json.phi;
  th.bang('Phí không hoàn khi hoàn tất', phi.trang_thai, 'Không hoàn');
});
